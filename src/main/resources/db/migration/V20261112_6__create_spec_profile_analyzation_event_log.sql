CREATE TABLE spec_profile_analyzation_event_log
(
    event_log_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sort_order                      INTEGER NOT NULL DEFAULT 0,
    status                          VARCHAR(20) NOT NULL,
    created_at                      TIMESTAMP NOT NULL DEFAULT now(),
    spec_profile_analyzation_run_id  BIGINT NOT NULL REFERENCES spec_profile_analyzation_run (run_id) ON DELETE CASCADE,
    CONSTRAINT uq_analyzation_event_order UNIQUE (spec_profile_analyzation_run_id, sort_order),
    CONSTRAINT ck_analyzation_event_order CHECK (sort_order >= 0),
    CONSTRAINT ck_analyzation_event_status CHECK (status IN ('QUEUED', 'IN_PROGRESS', 'CANCELED', 'COMPLETED', 'FAILED'))
);
