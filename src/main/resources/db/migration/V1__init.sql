-- =========================================================
-- LifeLog V1 init schema (PostgreSQL)
-- enum 값은 VARCHAR로 저장 (JPA @Enumerated(EnumType.STRING))
-- =========================================================

-- ---------------------------------------------------------
-- 회원 / 약관
-- ---------------------------------------------------------
CREATE TABLE member
(
    member_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL UNIQUE,
    status     VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE | INACTIVE | BANNED | DELETE_REGISTERED
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE member_identity
(
    member_identity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           VARCHAR(20)  NOT NULL DEFAULT 'LOCAL', -- LOCAL | GOOGLE | KAKAO
    provider_subject   VARCHAR(255) NOT NULL,
    password_hash      VARCHAR(255),                          -- 소셜 로그인은 NULL
    created_at         TIMESTAMP    NOT NULL DEFAULT now(),
    member_id          BIGINT       NOT NULL REFERENCES member (member_id) ON DELETE CASCADE,
    UNIQUE (provider, provider_subject)
);

CREATE TABLE term
(
    term_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(50) NOT NULL,
    version    INT         NOT NULL DEFAULT 1,
    content    TEXT        NOT NULL,
    required   BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP   NOT NULL DEFAULT now(),
    updated_at TIMESTAMP   NOT NULL DEFAULT now(),
    UNIQUE (type, version)
);

CREATE TABLE member_term
(
    member_term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    member_id      BIGINT    NOT NULL REFERENCES member (member_id) ON DELETE CASCADE,
    term_id        BIGINT    NOT NULL REFERENCES term (term_id),
    UNIQUE (member_id, term_id)
);

-- ---------------------------------------------------------
-- 마스터 데이터 (직무 / 전공 / 자격증 / 어학시험)
-- ---------------------------------------------------------
CREATE TABLE job
(
    job_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    main_category_code   VARCHAR(1)   NOT NULL, -- 대분류 (한국고용직업분류)
    main_category_name   VARCHAR(100) NOT NULL,
    middle_category_code VARCHAR(2)   NOT NULL, -- 중분류
    middle_category_name VARCHAR(100) NOT NULL,
    sub_category_code    VARCHAR(3)   NOT NULL, -- 소분류
    sub_category_name    VARCHAR(100) NOT NULL,
    code                 VARCHAR(4)   NOT NULL UNIQUE, -- 세분류 4자리
    name                 VARCHAR(100) NOT NULL
);

CREATE TABLE major
(
    major_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field               VARCHAR(30)  NOT NULL, -- 인문 | 사회 | 자연 | 공학 | 의약 | 교육 | 예체능 | 사관·경찰 | 기타
    name                VARCHAR(100) NOT NULL,
    code                VARCHAR(20)  NOT NULL UNIQUE,
    degree_process_name VARCHAR(20)  NOT NULL  -- 학사 | 전문학사 | 석사 | 석사+박사
);

CREATE TABLE certificate
(
    certificate_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(30)  NOT NULL, -- NATIONAL_PROFESSIONAL | NATIONAL_TECHNICAL | INTERNATIONAL | PRIVATE
    main_category   VARCHAR(5),            -- A ~ W (KRIVET 대분류), KRIVET 외 자격증은 NULL
    middle_category SMALLINT,
    name            VARCHAR(150) NOT NULL,
    code            VARCHAR(20) UNIQUE,    -- KRIVET 코드, AWS 등 KRIVET 외 자격증은 NULL
    issuer          VARCHAR(200),          -- 공인기관
    exam_fee        INT,                   -- 응시료(원)
    prep_months     SMALLINT               -- 평균 준비 기간(월)
);

CREATE TABLE language_exam
(
    language_exam_id BIGINT PRIMARY KEY,   -- 기준 CSV의 ID를 그대로 사용
    name             VARCHAR(50) NOT NULL UNIQUE,
    language_type    VARCHAR(20) NOT NULL, -- ENGLISH | JAPANESE | CHINESE | SPANISH | RUSSIAN | KOREAN | VIETNAMESE
    score_type       VARCHAR(20) NOT NULL  -- NUMERIC | GRADE | NUMERIC_AND_GRADE | NONE
);

CREATE TABLE language_cefr_mapping
(
    language_cefr_mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_exam_id         BIGINT   NOT NULL REFERENCES language_exam (language_exam_id),
    score_min                INT,              -- 숫자형 시험
    score_max                INT,
    score_grade              VARCHAR(20),      -- 등급형 시험
    cefr_level               SMALLINT NOT NULL -- 1(A1) ~ 6(C2)
);

-- ---------------------------------------------------------
-- 희망 직무
-- ---------------------------------------------------------
CREATE TABLE desired_job
(
    desired_job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    job_id         BIGINT    NOT NULL REFERENCES job (job_id),
    member_id      BIGINT    NOT NULL REFERENCES member (member_id) ON DELETE CASCADE,
    UNIQUE (member_id, job_id)
);

-- ---------------------------------------------------------
-- 스펙
-- ---------------------------------------------------------
CREATE TABLE spec_profile
(
    spec_profile_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporary_stored     BOOLEAN     NOT NULL DEFAULT TRUE,
    type                 VARCHAR(20) NOT NULL DEFAULT 'CURRENT', -- CURRENT | TARGET
    birth_year           SMALLINT,
    residence_region     VARCHAR(20),                            -- 17개 시도
    target_option_key    VARCHAR(30),                            -- TARGET 전용: INTERNSHIP | CERTIFICATE | GRADUATE_SCHOOL ...
    target_job_id        BIGINT REFERENCES job (job_id),         -- TARGET 전용
    created_at           TIMESTAMP   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMP   NOT NULL DEFAULT now(),
    member_id            BIGINT      NOT NULL REFERENCES member (member_id) ON DELETE CASCADE,
    base_spec_profile_id BIGINT REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE, -- TARGET이면 원본 CURRENT
    UNIQUE (member_id, type)                                     -- 회원당 CURRENT 1개, TARGET 1개
);

CREATE TABLE academic_ability
(
    academic_ability_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                  VARCHAR(20)  NOT NULL, -- HIGH_SCHOOL | COLLEGE | UNIVERSITY | GRADUATE_SCHOOL | ETC
    school_name           VARCHAR(100),
    status                VARCHAR(30)  NOT NULL, -- ATTENDING | LEAVE_FROM_SCHOOL | GRADUATE_POSTPONED | GRADUATED
    location              VARCHAR(20)  NOT NULL, -- 17개 시도
    university_grade      NUMERIC(3, 2),         -- 4.5 만점
    graduate_school_grade VARCHAR(2),            -- A+ ~ F
    graduated_at          DATE,                  -- 졸업(예정)월, 일은 1일로 저장
    created_at            TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMP    NOT NULL DEFAULT now(),
    spec_profile_id       BIGINT       NOT NULL REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE
);

CREATE TABLE academic_ability_major
(
    academic_ability_major_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_ability_id       BIGINT NOT NULL REFERENCES academic_ability (academic_ability_id) ON DELETE CASCADE,
    major_id                  BIGINT NOT NULL REFERENCES major (major_id),
    UNIQUE (academic_ability_id, major_id)
);

CREATE TABLE spec_profile_certificate
(
    spec_profile_certificate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acquired_at                 DATE   NOT NULL,
    spec_profile_id             BIGINT NOT NULL REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE,
    certificate_id              BIGINT NOT NULL REFERENCES certificate (certificate_id),
    UNIQUE (spec_profile_id, certificate_id)
);

CREATE TABLE language_exam_score
(
    language_exam_score_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_numeric          NUMERIC(6, 1),
    score_grade            VARCHAR(20),
    acquired_at            DATE   NOT NULL,
    spec_profile_id        BIGINT NOT NULL REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE,
    language_exam_id       BIGINT NOT NULL REFERENCES language_exam (language_exam_id)
);

CREATE TABLE experience
(
    experience_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(20)  NOT NULL, -- INTERNSHIP | PROJECT | CONTEST | CLUB | PRACTICUM | TRAINING | OPEN_SOURCE | ETC
    title           VARCHAR(150) NOT NULL,
    duration_months SMALLINT     NOT NULL,
    started_at      DATE,
    ended_at        DATE,
    description     VARCHAR(500),
    awarded         BOOLEAN      NOT NULL DEFAULT FALSE,
    organizer_name  VARCHAR(200),
    award_grade     VARCHAR(50),
    scope           VARCHAR(20),           -- CAMPUS | NATIONAL (공모전 규모)
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT now(),
    spec_profile_id BIGINT       NOT NULL REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 스펙 진단 (예측 결과)
-- ---------------------------------------------------------
CREATE TABLE spec_profile_analyzation_run
(
    spec_profile_analyzation_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version                   VARCHAR(50),
    created_at                      TIMESTAMP NOT NULL DEFAULT now(),
    delete_at                       TIMESTAMP,  -- 보관 만료 시각
    spec_profile_id                 BIGINT    NOT NULL REFERENCES spec_profile (spec_profile_id) ON DELETE CASCADE,
    job_id                          BIGINT REFERENCES job (job_id)
);

CREATE TABLE spec_profile_analyzation_result
(
    spec_profile_analyzation_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annual                             SMALLINT NOT NULL DEFAULT 0, -- 0 = 첫 취업, N = N년 차
    annual_income_min                  BIGINT   NOT NULL,
    annual_income_expected             BIGINT   NOT NULL,
    annual_income_max                  BIGINT   NOT NULL,
    percentile                         SMALLINT,                    -- 상위 %
    spec_profile_analyzation_run_id    BIGINT   NOT NULL REFERENCES spec_profile_analyzation_run (spec_profile_analyzation_run_id) ON DELETE CASCADE,
    UNIQUE (spec_profile_analyzation_run_id, annual)
);

-- ---------------------------------------------------------
-- 시뮬레이터 기준값
-- ---------------------------------------------------------
CREATE TABLE simulation_option_cost
(
    simulation_option_cost_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_key                VARCHAR(30)  NOT NULL UNIQUE, -- CERTIFICATE | INTERNSHIP | GRADUATE_SCHOOL | LANGUAGE | CONTEST
    title                     VARCHAR(100) NOT NULL,
    subtitle                  VARCHAR(200),
    tag                       VARCHAR(50),
    prep_months               SMALLINT     NOT NULL,
    estimated_cost            BIGINT       NOT NULL DEFAULT 0,
    cost_note                 VARCHAR(200),
    fit_description           VARCHAR(200)
);

-- ---------------------------------------------------------
-- 채용
-- ---------------------------------------------------------
CREATE TABLE company
(
    company_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    industry_code VARCHAR(20)  NOT NULL,
    size_type     VARCHAR(20),
    homepage_url  VARCHAR(500),
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE job_posting
(
    job_posting_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(200) NOT NULL,
    employment_type   VARCHAR(20)  NOT NULL, -- FULL_TIME | CONTRACT | INTERN
    career_type       VARCHAR(20)  NOT NULL, -- NEW | EXPERIENCED | ANY
    career_min_months SMALLINT,
    career_max_months SMALLINT,
    region_code       VARCHAR(30)  NOT NULL,
    workplace_address VARCHAR(255) NOT NULL,
    responsibilities  TEXT,
    description       TEXT,
    published_at      TIMESTAMP,
    deadline_type     VARCHAR(20)  NOT NULL, -- FIXED | ALWAYS | UNTIL_FILLED
    closes_at         TIMESTAMP,
    status            VARCHAR(10)  NOT NULL DEFAULT 'OPEN', -- OPEN | CLOSE
    source            VARCHAR(50)  NOT NULL,
    external_id       VARCHAR(150) NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP    NOT NULL DEFAULT now(),
    company_id        BIGINT       NOT NULL REFERENCES company (company_id),
    UNIQUE (source, external_id)
);

CREATE TABLE job_posting_job
(
    job_posting_job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id             BIGINT NOT NULL REFERENCES job (job_id),
    job_posting_id     BIGINT NOT NULL REFERENCES job_posting (job_posting_id) ON DELETE CASCADE,
    UNIQUE (job_posting_id, job_id)
);

CREATE TABLE job_posting_requirement
(
    job_posting_requirement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority                   VARCHAR(20)  NOT NULL, -- REQUIRED | PREFERRED
    type                       VARCHAR(20)  NOT NULL, -- MAJOR | DEGREE | SKILL | EXPERIENCE | CERTIFICATE | LANGUAGE | ETC
    content                    VARCHAR(500) NOT NULL,
    sort_order                 SMALLINT     NOT NULL DEFAULT 1,
    created_at                 TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMP    NOT NULL DEFAULT now(),
    job_posting_id             BIGINT       NOT NULL REFERENCES job_posting (job_posting_id) ON DELETE CASCADE
);

CREATE TABLE job_posting_pay
(
    job_posting_pay_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage              VARCHAR(20) NOT NULL, -- CURRENT | AFTER_CONVERSION (정규직 전환 후)
    pay_policy         VARCHAR(20) NOT NULL, -- SPECIFIED | COMPANY_POLICY | NEGOTIABLE
    pay_period         VARCHAR(20) NOT NULL, -- YEARLY | MONTHLY | HOURLY
    amount_min         BIGINT,               -- 회사 내규·협의면 NULL
    amount_max         BIGINT,
    description        VARCHAR(255),
    job_posting_id     BIGINT      NOT NULL REFERENCES job_posting (job_posting_id) ON DELETE CASCADE
);

CREATE TABLE job_posting_bookmark
(
    job_posting_bookmark_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMP NOT NULL DEFAULT now(),
    member_id               BIGINT    NOT NULL REFERENCES member (member_id) ON DELETE CASCADE,
    job_posting_id          BIGINT    NOT NULL REFERENCES job_posting (job_posting_id) ON DELETE CASCADE,
    UNIQUE (member_id, job_posting_id)
);

-- ---------------------------------------------------------
-- FK 조회용 인덱스
-- ---------------------------------------------------------
CREATE INDEX idx_member_identity_member ON member_identity (member_id);
CREATE INDEX idx_spec_profile_base ON spec_profile (base_spec_profile_id);
CREATE INDEX idx_academic_ability_spec ON academic_ability (spec_profile_id);
CREATE INDEX idx_spec_profile_certificate_cert ON spec_profile_certificate (certificate_id);
CREATE INDEX idx_language_exam_score_spec ON language_exam_score (spec_profile_id);
CREATE INDEX idx_experience_spec ON experience (spec_profile_id);
CREATE INDEX idx_analyzation_run_spec ON spec_profile_analyzation_run (spec_profile_id);
CREATE INDEX idx_language_cefr_mapping_exam ON language_cefr_mapping (language_exam_id);
CREATE INDEX idx_job_posting_company ON job_posting (company_id);
CREATE INDEX idx_job_posting_status_closes ON job_posting (status, closes_at);
CREATE INDEX idx_job_posting_requirement_posting ON job_posting_requirement (job_posting_id);
CREATE INDEX idx_job_posting_pay_posting ON job_posting_pay (job_posting_id);
