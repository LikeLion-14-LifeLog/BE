package com.lifelog.domain.certification;
import com.lifelog.domain.certification.dto.*;
import com.lifelog.domain.certification.entity.Certification;
import com.lifelog.domain.certification.enums.*;
import com.lifelog.domain.certification.mapper.CertificationMapper;
import com.lifelog.domain.certification.repository.CertificationRepository;
import com.lifelog.domain.certification.service.*;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.persistence.autoconfigure.EntityScan;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.*;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.jdbc.core.JdbcTemplate;
import java.util.*;
import java.util.concurrent.*;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.BDDMockito.given;
@SpringBootTest(classes = CertificationInitServiceTest.TestApplication.class, webEnvironment = SpringBootTest.WebEnvironment.NONE)
@ActiveProfiles("test")
class CertificationInitServiceTest {
    @Autowired CertificationService service;
    @Autowired CertificationRepository repository;
    @Autowired JdbcTemplate jdbc;
    @MockitoBean CertificationCsvReader reader;
    @BeforeEach void prepare() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS certificate (certificate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type VARCHAR(30) NOT NULL, main_category VARCHAR(50) NOT NULL, name VARCHAR(50) NOT NULL, code VARCHAR(10) UNIQUE, authorized_institution_name VARCHAR(50))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS certification_init_lock(id INTEGER PRIMARY KEY)");
        jdbc.execute("MERGE INTO certification_init_lock KEY(id) VALUES (1)");
        given(reader.read()).willReturn(List.of(row("코드자격", "A01011-30"), row("무코드자격", null)));
    }
    @AfterEach void clean() { repository.deleteAllInBatch(); }
    private CertificationCsvRow row(String name, String code) {
        return new CertificationCsvRow(name, code, CertificationMainCategory.COMMON, CertificationType.PRIVATE, null);
    }
    @Test @DisplayName("재실행은 동일 건수로 집계하고 PK·원본 밖 행을 보존한다")
    void 재실행_ID보존_성공() {
        // given
        assertThat(service.initFromCsv().createdCount()).isEqualTo(2);
        var ids = repository.findAll().stream().map(Certification::getId).toList();
        jdbc.update("INSERT INTO certificate(type,main_category,name) VALUES ('PRIVATE','COMMON','원본밖')");
        // when
        var result = service.initFromCsv();
        // then
        assertThat(result).isEqualTo(CertificationInitResDto.create(2,0,0,2));
        assertThat(repository.findAll().stream().map(Certification::getId)).containsAll(ids);
        assertThat(repository.count()).isEqualTo(3);
    }
    @Test @DisplayName("코드 보완과 기관명 변경 시 기존 PK를 유지한다")
    void 코드보완_변경집계_성공() {
        // given
        service.initFromCsv();
        var id = repository.findAll().stream().filter(c -> c.getCode() == null).findFirst().orElseThrow().getId();
        given(reader.read()).willReturn(List.of(new CertificationCsvRow("무코드자격", "A99999-30", CertificationMainCategory.COMMON, CertificationType.PRIVATE, "기관")));
        // when
        var result = service.initFromCsv();
        // then
        assertThat(result.updatedCount()).isEqualTo(1);
        assertThat(repository.findById(id).orElseThrow().getCode()).isEqualTo("A99999-30");
    }
    @Test @DisplayName("실제 DB 실패 시 신규 등록과 기존 변경을 전체 롤백한다")
    void 저장실패_롤백_성공() {
        // given
        service.initFromCsv();
        given(reader.read()).willReturn(List.of(row("변경이름", "A01011-30"), row("신규", "A00001-30"), row("가".repeat(51), "A00002-30")));
        // when / then
        assertThatThrownBy(service::initFromCsv).isInstanceOf(com.lifelog.global.exception.CustomException.class);
        assertThat(repository.count()).isEqualTo(2);
        assertThat(repository.findAll()).extracting(Certification::getName).contains("코드자격");
    }
    @Test @DisplayName("독립 트랜잭션의 동시 초기화는 중복을 생성하지 않는다")
    void 동시호출_성공() throws Exception {
        // given
        var barrier = new CyclicBarrier(2);
        given(reader.read()).willAnswer(inv -> { barrier.await(5, TimeUnit.SECONDS); return List.of(row("무코드", null)); });
        // when
        try (var executor = Executors.newFixedThreadPool(2)) {
            var a = executor.submit(service::initFromCsv); var c = executor.submit(service::initFromCsv);
            var first = a.get(20, TimeUnit.SECONDS); var second = c.get(20, TimeUnit.SECONDS);
            // then
            assertThat(first.createdCount() + second.createdCount()).isEqualTo(1);
            assertThat(first.unchangedCount() + second.unchangedCount()).isEqualTo(1);
            assertThat(repository.count()).isEqualTo(1);
        }
    }
    @Configuration(proxyBeanMethods = false) @EnableAutoConfiguration
    @EntityScan(basePackageClasses = Certification.class)
    @EnableJpaRepositories(basePackageClasses = CertificationRepository.class)
    @Import({CertificationService.class, CertificationInitService.class, CertificationMapper.class})
    static class TestApplication {}
}
